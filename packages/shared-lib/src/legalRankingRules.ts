/**
 * Пометка на странице товара: площадка не является продавцом.
 *
 * @param sellerName отображаемое имя продавца; пустое — без имени
 */
export function buildMarketplaceNotSellerNotice(
  sellerName: string | null | undefined,
): string {
  const name = typeof sellerName === "string" ? sellerName.trim() : "";
  if (!name) {
    return "Gitorg — площадка, а не продавец. За товар, его описание и передачу отвечает продавец.";
  }
  return `Gitorg — площадка, а не продавец. Товар продаёт ${name}: он отвечает за товар, его описание и передачу.`;
}
